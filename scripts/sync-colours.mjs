// Copies the game's colours into src/gameColours.ts, grouped by ramp. Run on the PC: npm run colours.
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync(new URL("../../game-claude/src/palette.ts", import.meta.url), "utf8");
const list = (name) => src.match(new RegExp(`${name} = \\[([^\\]]*)\\]`))[1].match(/#[0-9A-Fa-f]{6}/g).map((c) => c.toUpperCase());
const ids = [...list("PALETTE"), ...list("DETAIL")];
// Colour id ranges from the comments in palette.ts (id 8 = DETAIL[0]); ids not listed fall into Other.
const GROUPS = [
  ["Master", [0, 7]], ["Lush grass", [8, 10]], ["Dry grass", [11, 13]], ["Flowers", [16, 18], [26, 26]], ["Stone", [19, 22]],
  ["Ice", [23, 25]], ["Olive", [27, 30]], ["Sand", [31, 32]], ["Water", [33, 36]], ["Mudflat", [37, 39]], ["Marsh", [40, 42]], ["Leaf", [44, 48]],
];
const used = new Set();
const groups = GROUPS.map(([name, ...ranges]) => {
  const colours = [];
  for (const [a, b] of ranges) for (let i = a; i <= b; i++) {
    used.add(i);
    colours.push(ids[i]);
  }
  return { name, colours };
});
groups.push({ name: "Other", colours: ids.filter((_, i) => !used.has(i)) });
const seen = new Set();
for (const g of groups) g.colours = g.colours.filter((c) => !seen.has(c) && seen.add(c));
const body = groups.map((g) => `  { name: ${JSON.stringify(g.name)}, colours: ${JSON.stringify(g.colours)} },`).join("\n");
writeFileSync(new URL("../src/gameColours.ts", import.meta.url), `// Generated by scripts/sync-colours.mjs from the game's src/palette.ts. Do not edit by hand.
export type Group = { name: string; colours: string[] };

export const GAME_COLOURS: Group[] = [
${body}
];
`);
console.log(`${ids.length} game colours, ${seen.size} unique`);
